# -*- coding: utf-8 -*-
"""v12「配電盤」の部品。★blender_kit.py の名前空間で exec される前提
(Build / mat / export / math / E がそこから来る)。単体では動かない。

★原点の規約(ここを間違えると gen_stages.py の座標が全部ずれる):
  ・breaker / busboard / socket / turn / stepblk / blast … 原点 = 【床の中心】。+Z を向く
  ・lever   … 原点 = 【軸(ピボット)】。腕は +Y へ伸びる。Lua が rotation.x で倒す
  ・lamp    … 原点 = 【レンズの中心】。+Z を向く。色は実行時に scene:setColor で塗る
  ・walkway … 原点 = 【踏面の中心】。構造は原点より下。歩く高さへそのまま置ける
  ・shard   … 原点 = 中心。幅 1 x 高さ 1 の【単位トラス】。gen が引き延ばして使う
  ・cable   … 原点 = 左端の留め具。+X へ 6m 垂れる

★寸法の物差し(既存): ベンチ 0.95 / ドラム缶 0.88 / ロッカー 1.95 / 棚 2.40。
  新しい物もこの中に収める。ここを外すと部屋の大きさが読めなくなる。
"""


def build_v12():
    M_METAL = mat("jx_metal", "metal_col.png", 0.45, 0.6)
    M_PAINT = mat("jx_paint", "paint_col.png", 0.55)
    M_DARK = mat("jx_dark", "dark_col.png", 0.98)
    M_PLAIN = mat("jx_plain", "plain_col.png", 0.55)
    M_CONC = mat("jx_conc", "concrete_col.png", 0.92, 0.0, "concrete_nrm.png")

    # ======================= breaker(継電器) 高さ 1.45m =======================
    # ★ベンチ 0.95 と ロッカー 1.95 の間 = 腰の高さの操作盤に見える寸法。
    b = Build()
    b.ebox((0.0, 0.07, 0.0), (1.16, 0.14, 0.66), 0, 1.0)                  # 台座
    b.ebox((0.0, 0.62, 0.02), (0.94, 1.02, 0.46), 1, 1.0)                 # 筐体
    b.ebox((0.0, 1.19, 0.0), (1.02, 0.12, 0.56), 0, 1.0)                  # 天板
    b.ebox((0.0, 1.31, -0.02), (0.34, 0.14, 0.34), 0, 1.0)                # 軸受け
    b.ebox((0.0, 0.86, 0.24), (0.70, 0.30, 0.03), 0, 1.0)                 # 目盛り板
    b.ebox((0.0, 0.46, 0.24), (0.70, 0.12, 0.03), 3, 1.0)                 # 銘板
    for sx in (-1, 1):                                                    # 側面の電線管
        b.etube([(0.0, 0.075), (0.62, 0.075)], 0, axis="y",
                origin=(sx * 0.55, 0.0, -0.22), seg=10)
        b.ebox((sx * 0.55, 0.66, -0.22), (0.20, 0.09, 0.20), 0, 1.0)
    for sx in (-1, 1):
        for sz in (-1, 1):
            b.ebox((sx * 0.50, 0.03, sz * 0.26), (0.12, 0.06, 0.12), 0, 1.0)
    export(b.make("jx_breaker", [M_METAL, M_PAINT, M_DARK, M_PLAIN]), "breaker.gltf")

    # ======================= lever(継電器の腕) 長さ 0.66m =======================
    # 原点 = 軸。立っている時は +Y。Lua が rotation.x を 0 -> 78 度にして倒す。
    b = Build()
    b.etube([(0.0, 0.05), (0.50, 0.05)], 0, axis="y", origin=(0, 0, 0), seg=10)
    b.ebox((0.0, 0.10, 0.0), (0.16, 0.10, 0.16), 0, 1.0)                  # 根元の錘
    b.etube([(0.50, 0.0), (0.54, 0.10), (0.62, 0.10), (0.66, 0.0)], 1,
            axis="y", origin=(0, 0, 0), seg=12)                           # 握り
    export(b.make("jx_lever", [M_METAL, M_PAINT]), "lever.gltf")

    # ======================= busboard(配電盤) 4.6 x 2.82 =======================
    b = Build()
    b.ebox((0.0, 0.09, 0.0), (4.60, 0.18, 0.72), 0, 1.0)                  # 基礎
    b.ebox((0.0, 1.44, 0.0), (4.36, 2.52, 0.58), 1, 1.0)                  # 箱
    b.ebox((0.0, 2.74, 0.0), (4.52, 0.16, 0.68), 0, 1.0)                  # 笠木
    for i in range(5):                                                    # 5 つの計器窓
        x = -1.6 + i * 0.8
        b.ebox((x, 1.86, 0.30), (0.62, 0.62, 0.05), 0, 1.0)               # 窓枠
        b.ebox((x, 1.86, 0.33), (0.50, 0.50, 0.02), 2, 1.0)               # 窓の底(暗い)
        b.ebox((x, 1.36, 0.30), (0.56, 0.14, 0.04), 3, 1.0)               # 銘板
        b.ebox((x, 1.06, 0.30), (0.10, 0.30, 0.06), 0, 1.0)               # 端子の柱
        b.etube([(2.62, 0.07), (3.60, 0.07)], 0, axis="y",
                origin=(x, 0.0, -0.18), seg=10)                           # 天井へ抜ける管
    for sx in (-1, 1):                                                    # 下段の点検扉
        b.ebox((sx * 1.06, 0.62, 0.30), (1.90, 0.86, 0.04), 0, 1.0)
        b.ebox((sx * 1.86, 0.62, 0.33), (0.08, 0.34, 0.04), 0, 1.0)
    export(b.make("jx_busboard", [M_METAL, M_PAINT, M_DARK, M_PLAIN]), "busboard.gltf")

    # ======================= lamp(表示灯) 直径 0.42 =======================
    # ★原点 = レンズの中心。消えている時は暗い灰、点くと色が乗る(実行時に塗る)。
    b = Build()
    b.etube([(-0.06, 0.21), (0.0, 0.21), (0.02, 0.19)], 0, axis="z",
            origin=(0, 0, 0), seg=18)
    b.etube([(0.02, 0.0), (0.02, 0.18), (0.06, 0.17), (0.09, 0.10), (0.10, 0.0)], 1,
            axis="z", origin=(0, 0, 0), seg=18)                           # レンズ
    export(b.make("jx_lamp", [M_METAL, M_PLAIN]), "lamp.gltf")

    # ======================= blast(出口の扉・片側) 2.1 x 4.6 =======================
    # 原点 = 床・扉の中心。2 枚を左右に置き、開く時は左右へ滑らせる。
    b = Build()
    W2, H2, T2 = 2.10, 4.60, 0.34
    b.ebox((0.0, H2 * 0.5, 0.0), (W2, H2, T2), 0, 1.0)
    for i in range(5):                                                    # 補強のリブ
        b.ebox((0.0, 0.45 + i * 0.92, T2 * 0.5 + 0.05), (W2 - 0.16, 0.22, 0.12), 1, 1.0)
    b.ebox((0.0, H2 * 0.5, -T2 * 0.5 - 0.04), (W2 - 0.30, H2 - 0.30, 0.08), 1, 1.0)
    for sy in (0.8, 3.8):                                                 # 蝶番の柱
        b.etube([(-0.20, 0.16), (0.20, 0.16)], 0, axis="y",
                origin=(-W2 * 0.5 + 0.10, sy, 0.0), seg=12)
    b.ebox((W2 * 0.5 - 0.22, 2.30, T2 * 0.5 + 0.06), (0.26, 1.10, 0.14), 0, 1.0)
    export(b.make("jx_blast", [M_METAL, M_PAINT]), "blast.gltf")

    # ======================= socket(玉の受け皿) 直径 2.12 =======================
    # ★縁 0.10 は玉(半径 0.36)がゆっくり来ると越えられない高さ = 勢いが要る。
    #   内側は中心へ下る皿。一度入ると出ない。
    b = Build()
    b.etube([(0.0, 0.98), (0.10, 0.98), (0.115, 0.82), (0.035, 0.34), (0.02, 0.0)],
            0, axis="y", origin=(0, 0, 0), seg=28)
    b.etube([(0.0, 1.06), (0.05, 1.06), (0.05, 0.98)], 1, axis="y",
            origin=(0, 0, 0), seg=28)
    for i in range(6):                                                    # 留め具
        a = 2 * math.pi * i / 6
        b.ebox((math.cos(a) * 1.02, 0.03, math.sin(a) * 1.02), (0.16, 0.06, 0.16), 0, 1.0)
    export(b.make("jx_socket", [M_METAL, M_PAINT]), "socket.gltf")

    # ======================= walkway(実体化する橋) 2.4 x 10.0 =======================
    # ★原点 = 【踏面の中心】。構造は原点より下。歩く高さへそのまま置ける。
    b = Build()
    LW, LL = 2.40, 10.0
    b.ebox((0.0, -0.05, 0.0), (LW, 0.10, LL), 0, 1.0)                     # 踏面
    for i in range(21):
        z = -LL * 0.5 + LL * i / 20.0
        b.ebox((0.0, -0.13, z), (LW, 0.08, 0.10), 0, 1.0)                 # 桟
    for sx in (-1, 1):
        b.ebox((sx * (LW * 0.5 - 0.06), -0.22, 0.0), (0.12, 0.34, LL), 1, 1.0)   # 主桁
        b.ebox((sx * (LW * 0.5 - 0.03), 0.52, 0.0), (0.06, 0.06, LL), 0, 1.0)    # 手すり
        for i in range(6):
            z = -LL * 0.5 + LL * i / 5.0
            b.ebox((sx * (LW * 0.5 - 0.03), 0.26, z), (0.06, 0.55, 0.06), 0, 1.0)
    export(b.make("jx_walkway", [M_METAL, M_PAINT]), "walkway.gltf")

    # ======================= shard(欠片) 単位トラス 1 x 1 =======================
    # ★幅 1 x 高さ 1 x 厚み 0.12。gen が引き延ばして 3 枚を別々の距離に吊る。
    #   或る一点から見ると 3 枚の輪郭がつながって【1 本のトラス橋】に見える。
    b = Build()
    b.ebox((0.0, 0.46, 0.0), (1.0, 0.08, 0.12), 0, 1.0)                   # 上弦
    b.ebox((0.0, -0.46, 0.0), (1.0, 0.08, 0.12), 0, 1.0)                  # 下弦
    for sx in (-1, 1):
        b.ebox((sx * 0.46, 0.0, 0.0), (0.08, 0.84, 0.12), 0, 1.0)         # 縦材
    for sx in (-1, 1):                                                    # 斜材
        n = 22
        for i in range(n):
            t = -0.42 + 0.84 * i / (n - 1.0)
            b.ebox((sx * t * 1.02, t * 1.0, 0.0), (0.075, 0.075, 0.11), 1, 1.0)
    export(b.make("jx_shard", [M_METAL, M_PAINT]), "shard.gltf")

    # ======================= turn(回転台) 直径 3.6 =======================
    b = Build()
    b.etube([(0.0, 1.80), (0.14, 1.80), (0.16, 1.72)], 0, axis="y",
            origin=(0, 0, 0), seg=32)
    b.etube([(0.16, 0.0), (0.16, 1.72)], 1, axis="y", origin=(0, 0, 0), seg=32)
    for i in range(8):                                                    # 放射のリブ
        a = 2 * math.pi * i / 8
        b.ebox((math.cos(a) * 0.95, 0.175, math.sin(a) * 0.95), (0.14, 0.03, 1.60), 0, 1.0)
    b.etube([(0.16, 0.0), (0.24, 0.34), (0.26, 0.30)], 0, axis="y",
            origin=(0, 0, 0), seg=20)                                     # 軸のふくらみ
    export(b.make("jx_turn", [M_METAL, M_PAINT]), "turn.gltf")

    # ======================= stepblk(見張りの間の段板) 2.6 x 0.62 =======================
    b = Build()
    b.ebox((0.0, 0.28, 0.0), (2.60, 0.56, 2.60), 0, 1.0)
    b.ebox((0.0, 0.585, 0.0), (2.44, 0.05, 2.44), 1, 1.0)                 # 天板の縁取り
    for sx in (-1, 1):
        b.ebox((sx * 1.24, 0.28, 0.0), (0.12, 0.50, 2.44), 1, 1.0)
    export(b.make("jx_stepblk", [M_CONC, M_METAL]), "stepblk.gltf")

    # ======================= cable(垂れるケーブル) 6m =======================
    # ★原点 = 左端の留め具。+X へ 6m。継電器と配電盤を【線でつなぐ】ための飾り。
    b = Build()
    SPAN2, SAG, N = 6.0, 0.55, 16
    prof = [(t / float(N) * SPAN2, -SAG * 4.0 * (t / float(N)) * (1.0 - t / float(N)))
            for t in range(N + 1)]
    for i in range(N):
        (x0, y0), (x1, y1) = prof[i], prof[i + 1]
        L = math.hypot(x1 - x0, y1 - y0)
        b.ebox(((x0 + x1) * 0.5, (y0 + y1) * 0.5, 0.0), (L + 0.02, 0.11, 0.11), 0, 1.0)
    for x in (0.0, SPAN2):
        b.ebox((x, 0.0, 0.0), (0.20, 0.24, 0.20), 1, 1.0)
    export(b.make("jx_cable", [M_DARK, M_METAL]), "cable.gltf")
