# -*- coding: utf-8 -*-
"""第三幕の作り直し（人間の尺度版）。gen_liminal から import して使う。

★なぜ作り直したか
  前の第三幕は 58 x 42m・高さ 28m の縦穴 1 つだった。足の下に 17m の水があり、
  天井まで 28m。絵としては効くが【巨大すぎて部屋として読めない】。
  ここでは同じ 5 本の継ぎ目を、天井 4m の部屋 4 つ + 廊下 1 本へ入れ直す。
  体積で約 20 分の 1。

★前後の受け渡しは 1mm も動かさない（通しで遊べる状態を保つため）:
    入口 … 南壁 z=SZ0 の開口。中心 x=22.0、下端 y=Y3
    出口 … 北壁 z=SZ1 の開口。中心 x=68.0(XITX)、下端 y=Y4 = Y3+1.80
  この 2 点さえ合っていれば、第二幕と第四幕には一切触らなくてよい。

   平面(z が上へ増える。左が x 小)

     z=214  ┌─────────────── R4 ────────────────┐  出口(68, Y4)
            │  x 58..72  床 Y4  天井 +3.6        │  継ぎ目14 直視しない
            │                                    │  継ぎ目16 暗の一瞬
     z=196  └──────┬─────────────────────────────┘
     z=204  ┌──────┴── 廊下 x 30..58 z 200..204 ─┘  階段で Y3 -> Y4
     z=200  │
     z=206  ┌──────────────┐
            │ R3 x 16..30  │  継ぎ目13 かくれて合わせる
     z=196  ├──────────────┤
            │ R2 x 16..30  │  継ぎ目12 巡る
     z=184  ├──────────────┤
            │ R1 x 16..30  │  継ぎ目11 線にする
     z=172  └──────┬───────┘  入口(22, Y3)
"""


def build(G, Y3, DW, DH):
    """G は gen_liminal モジュール。名前空間を汚さないよう明示的に受け取る。"""
    box, glow, hit, plight = G.box, G.glow, G.hit, G.plight
    shell, wall_with_door, wall_hole = G.shell, G.wall_with_door, G.wall_hole
    troffer, mark, ent, Conn = G.troffer, G.mark, G.ent, G.Conn
    door_casing, exit_sign, bench = G.door_casing, G.exit_sign, G.bench
    T_CONC, T_PAINT, T_METAL = G.T_CONC, G.T_PAINT, G.T_METAL
    T_TILEF, T_TILEW, T_CEIL = G.T_TILEF, G.T_TILEW, G.T_CEIL
    WT, EYE, GOLD, WARM, COOL = G.WT, G.EYE, G.GOLD, G.WARM, G.COOL
    FRAME_COL = G.FRAME_COL

    EY = Y3 + EYE                  # 下の階の目の高さ
    Y4 = Y3 + 1.80                 # 出口の高さ(第四幕の床)
    EY4 = Y4 + EYE
    H1 = 4.00                      # 下の部屋の天井高
    H4 = 3.60                      # 上の部屋の天井高
    SZ0, SZ1 = 172.0, 214.0
    XITX, XITW, XITH = 68.0, 2.20, 2.40

    # ================================================================ R1+R2 入口の長室
    # ★R1 と R2 は【壁で仕切らない】。最初は 0.60m 上げた開口で仕切ったが、
    #   段差の向こう側は体の半径(0.34)ぶん壁に寄れないので【立てる升が一つも無く】、
    #   組み上げても越えられなかった(検査[2] が捕まえ、tops/blocked を実測して判った)。
    #   仕切りは【床の穴】でやる。渡す物と渡る先が同じ高さなら必ず通れる。
    shell("S3a", 16.0, 30.0, SZ0, 198.0, H1, T_CONC, T_PAINT, y=Y3, walls="we",
          ceil_tex=T_CEIL, floor=False)
    wall_with_door("S3a_s", "z", SZ0 - WT / 2, 16.0 - WT, 30.0 + WT, Y3, H1, 22.0, DW, DH, T_PAINT)
    wall_with_door("S3a_n", "z", 198.0 + WT / 2, 16.0 - WT, 30.0 + WT, Y3, H1, 21.0, DW, DH, T_PAINT)
    door_casing("S3a_nc", "z", 198.0 - 0.02, 21.0, Y3, DW, DH)
    # ★白い部屋(第二幕)の床は z=170.3 で終わる。渡りを 1 枚だけ、ぴったり足す
    box("S3a_in", (22.0, Y3 - WT / 2, 171.0), (3.6, WT, 1.4), T_CONC, "y",
        rough=0.95, solid=True)
    box("S3a_incil", (22.0, Y3 + 2.9 + WT / 2, 171.0), (3.6, WT, 1.4), T_CONC, "y", rough=0.94)
    for sgn in (-1, 1):
        box("S3a_inw%d" % sgn, (22.0 + sgn * 1.9, Y3 + 1.45, 171.0), (WT, 2.9, 1.4),
            T_CONC, "x", rough=0.9, solid=True)
    # 床は 3 枚。間の 2 か所が【継ぎ目 11 と 12 の穴】
    GAP1 = (182.6, 184.6)                 # 継ぎ目11 が渡す
    GAP2 = (191.0, 196.1)                 # 継ぎ目12 が踏み石を置く
    for nm, z0, z1 in (("f1", 171.7, GAP1[0]), ("f2", GAP1[1], GAP2[0]),
                       ("f3", GAP2[1], 198.3)):
        box("S3a_" + nm, (23.0, Y3 - WT / 2, (z0 + z1) / 2), (14.6, WT, z1 - z0),
            T_CONC, "y", rough=0.95, solid=True)
    # 穴の中(底と側面)。落ちても死なないが、登れないので戻るしかない
    for i, (z0, z1) in enumerate((GAP1, GAP2)):
        box("S3a_pit%d" % i, (23.0, Y3 - 1.20 - WT / 2, (z0 + z1) / 2),
            (14.0, WT, z1 - z0), T_CONC, "y", rough=0.95, solid=True)
        for sgn, xx in ((-1, 16.0), (1, 30.0)):
            box("S3a_pw%d_%d" % (i, sgn), (xx, Y3 - 0.60, (z0 + z1) / 2),
                (0.10, 1.20, z1 - z0), T_TILEW, "x", rough=0.4)
        # ★側面は渡す物の【外側】へ 0.05 逃がす。面をぴったり合わせると
        #   組み上がった踏み石・渡し板とめり込む(検査[8])
        for sgn, zz in ((-1, z0 - 0.05), (1, z1 + 0.05)):
            box("S3a_pf%d_%d" % (i, sgn), (23.0, Y3 - 0.60, zz), (14.0, 1.20, 0.10),
                T_TILEW, "z", rough=0.4)
    for z in (176.0, 181.0, 187.5, 194.5):
        troffer("S3a_tr%.1f" % z, 23.0, Y3 + H1, z, on=(z in (176.0, 194.5)))
    bench("S3a_bench", 18.2, Y3, 179.0, axis="z")
    for z in (186.0, 189.0):               # 長い部屋に柱で拍を入れる
        box("S3a_col%.0f" % z, (17.4, Y3 + H1 / 2, z), (0.55, H1, 0.55), T_CONC, "x",
            rough=0.9, solid=True)

    # ---- 継ぎ目 11「線にする」----
    # ★3 つの破片は材質をわざと変えてある(錆びた鉄 / 塗装 / コンクリ)。
    #   色が乗っている間は【3 つの無関係な塊】にしか見えない。彩度が抜けて輪郭だけに
    #   なると、同じ 1 枚の渡し板の断片だと分かる。レンズが無いと何を合わせるのか読めない。
    F11 = (19.60, EY, 178.40)
    c11 = Conn(11, F11, 3.2, 11.0, (23.0, Y3 + 0.2, 183.6), "coil",
               lens=dict(kind="outline", at=[round(v, 3) for v in F11],
                         r=6.4, r0=1.6, need=0.72))
    PCOL = ([0.52, 0.34, 0.26], [0.46, 0.48, 0.44], [0.60, 0.60, 0.57])
    PTEX = (T_METAL, T_PAINT, T_CONC)
    PRGH = (0.55, 0.45, 0.90)
    PMET = (0.55, 0.00, 0.00)
    for i, k in enumerate((0.42, 0.60, 0.80)):
        cx = 21.5 + 1.0 * i
        pl = box("C11_p%d" % i, (cx, Y3 - 0.11, 183.6), (1.00, 0.22, 2.00),
                 PTEX[i], "y", rough=PRGH[i], metal=PMET[i], color=PCOL[i], tile=(0.5, 1.0))
        g = glow("C11_g%d" % i, (cx, Y3 + 0.02, 183.6), (0.80, 0.04, 1.70), GOLD, 0.95)
        c11.shard(k, [pl, g], glows=[g])
        c11.solid(hit("C11_h%d" % i, (cx, Y3 - 0.11, 183.6), (1.00, 0.22, 2.00),
                      kinematic=True))
    mark("C11_mark", (F11[0], Y3 + 0.008, F11[2]), T_CONC, (0.74, 0.74, 0.72), rough=0.9)
    plight("C11_fill", (23.0, Y3 + 2.6, 180.0), WARM, 7.0, 11.0)

    # ---- 継ぎ目 12「巡る」----
    # ★破片ごとに別の立ち位置。3 か所を歩いて回ると、踏み石が 1 つずつ現れる。
    F12 = (27.00, EY, 186.00)
    c12 = Conn(12, F12, 2.4, 12.0, (23.0, Y3 + 0.2, 193.5), "visit-columns",
               needs=(11,), per_shard=True)
    # ★3 つの立ち位置は【全部 穴の手前】に置くこと。穴の中や向こう側へ置くと、
    #   渡るために解く物の焦点が「渡らないと踏めない」という循環になる。
    # ★3 つ目を踏み石の真正面(23.5, 186.9)に置いたら確定域が 24m2 になり、
    #   「歩いていて勝手に確定する」で弾かれた。近いほど角度が鈍くなるので、
    #   立ち位置は【斜めから・遠く】へ寄せる。
    C12F = ((27.00, 186.00), (18.60, 189.20), (28.20, 189.60))
    # ★踏み石は【ぴったり隣り合わせる】。隙間を空けると体(半径 0.34)が渡れない
    # ★k は【ずらし量】。1 に近いほど実体の近くに浮くので角度が鈍り、確定域が
    #   際限なく広がる(0.70 にしたら 24m2 になり「歩いていて勝手に確定する」で弾かれた)。
    #   3 つとも 0.5 前後に揃えて、どれも同じくらいの手応えにする。
    for i, (k, (fx, fz)) in enumerate(zip((0.36, 0.52, 0.44), C12F)):
        zc = GAP2[0] + 0.85 + i * 1.70
        col = box("C12_c%d" % i, (23.0, Y3 - 0.11, zc), (2.40, 0.22, 1.70),
                  T_CONC, "y", rough=0.88, color=[0.58, 0.58, 0.55], tile=(1.2, 0.85))
        g = glow("C12_g%d" % i, (23.0, Y3 + 0.02, zc), (2.00, 0.04, 1.40), GOLD, 1.05)
        c12.shard(k, [col, g], glows=[g], focus=(fx, EY, fz))
        c12.solid(hit("C12_h%d" % i, (23.0, Y3 - 0.11, zc), (2.40, 0.22, 1.70), kinematic=True))
        mark("C12_mk%d" % i, (fx, Y3 + 0.008, fz), T_CONC, (0.74, 0.74, 0.72), rough=0.9)
    plight("C12_fill", (23.0, Y3 + 2.8, 193.0), WARM, 7.5, 12.0)

    # ================================================================ R3 かくれる部屋
    shell("S3c", 16.0, 30.0, 198.6, 206.0, H1, T_CONC, T_PAINT, y=Y3, walls="wn",
          ceil_tex=T_CEIL)
    # 東壁の開口は床の高さ。ただし【開口の先に 2.6m ぶん床が無い】ので、
    # 継ぎ目13 が梁を架けるまで廊下へは渡れない。
    # ★最初 開口の下端を Y3+1.10 に、廊下の床の天端を Y3+0.55 にしていて
    #   高さが食い違っていた。渡す物と渡る先の高さは必ず一致させること。
    wall_hole("S3c_e", "x", 30.0 + WT / 2, 198.6 - WT, 206.0 + WT, Y3, Y3 + H1,
              202.0, 2.60, Y3, 2.40, T_PAINT)
    for z in (200.5, 204.5):
        troffer("S3c_tr%.1f" % z, 22.0, Y3 + H1, z, on=(z == 200.5))
    # 陰に使う太い立管。★これが無いと「隠す物」が無い
    box("S3c_pipe", (25.70, Y3 + H1 / 2, 201.50), (0.62, H1, 0.62), T_METAL, "x",
        rough=0.5, metal=0.55, color=[0.48, 0.48, 0.45], solid=True)

    # ---- 継ぎ目 13「かくれて合わせる」----
    # ★偽物(囮の梁)が立管の陰へ入る位置でだけ成立する。見えている限り決まらない。
    F13 = (24.10, EY, 203.60)
    LURE13 = (27.30, Y3 + 2.05, 199.40)
    c13 = Conn(13, F13, 3.6, 12.0, (29.0, Y3 + 1.6, 202.0), "hide-behind-mast",
               needs=(12,),
               occl=dict(p=[round(v, 3) for v in LURE13],
                         # ★遮蔽箱は【焦点と囮を結ぶ線の上】に無いと一度も成立しない。
                         #   最初 x=27.3 に置いたら線は x=25.9 を通っていて、
                         #   合う位置が床の上に一つも無かった(最小誤差 37.4°)。
                         boxes=[[25.70 - 0.33, Y3, 201.50 - 0.33,
                                 25.70 + 0.33, Y3 + H1, 201.50 + 0.33]]))
    box("S3c_lure", LURE13, (1.90, 0.20, 0.50), T_CONC, "y", rough=0.9,
        color=[0.56, 0.56, 0.53])
    # 渡す梁は 2 本。x 30.0〜32.6 の隙間を床の高さで埋める(天端が Y3 ちょうど)
    for i, k in enumerate((0.44, 0.66)):
        xx = 30.875 + i * 1.15
        bm = box("C13_b%d" % i, (xx, Y3 - 0.11, 202.0), (1.15, 0.22, 2.40),
                 T_METAL, "y", rough=0.5, metal=0.5, color=[0.50, 0.50, 0.47], tile=(0.58, 1.2))
        g = glow("C13_g%d" % i, (xx, Y3 + 0.02, 202.0), (0.90, 0.04, 2.10), GOLD, 1.05)
        c13.shard(k, [bm, g], glows=[g])
        c13.solid(hit("C13_h%d" % i, (xx, Y3 - 0.11, 202.0), (1.15, 0.22, 2.60),
                      kinematic=True))
    mark("C13_mark", (F13[0], Y3 + 0.008, F13[2]), T_CONC, (0.74, 0.74, 0.72), rough=0.9)
    plight("C13_fill", (22.0, Y3 + 2.8, 202.0), WARM, 7.0, 11.0)

    # ================================================================ 廊下(東西) + 階段
    # ★ここで Y3 -> Y4 の 1.80m を稼ぐ。6 段 x 0.30 = 1.80。またげる上限 0.32 未満。
    # ★天井は 4.60。2.80 にしたら、階段を登った先(Y4 = +1.80)の頭上が 1.00m しか
    #   残らず、体(頭上 1.80 必要)が立てなかった ── 登った所で詰む。
    #   上がる高さぶんだけ天井も上げること。
    shell("S3d", 30.0, 58.0, 200.0, 204.0, 4.60, T_CONC, T_PAINT, y=Y3, walls="ns",
          ceil_tex=T_CEIL, floor=False)
    # ★床は x=32.6 から。手前の 2.6m は【わざと空けてある】= 継ぎ目13 の梁の居場所
    box("S3d_flr", (45.3, Y3 - WT / 2, 202.0), (25.4, WT, 4.0), T_CONC, "y",
        rough=0.92, solid=True)
    # 段(x=44.0 から東へ 6 段)
    for i in range(6):
        yy = Y3 + 0.30 * (i + 1)
        x0 = 44.0 + 0.90 * i
        box("S3d_st%d" % i, (x0 + 0.45, yy - 0.15, 202.0), (0.90, 0.30, 3.40),
            T_CONC, "y", rough=0.9, color=[0.62, 0.62, 0.58], solid=True)
    # ★踊り場は【最後の段から R4 の壁まで】途切れずに敷く。
    #   50.4〜56.0 で止めたら、段との間に 1.0m、壁との間に 2.0m の欠けが残った。
    box("S3d_land", (53.55, Y4 - WT / 2, 202.0), (8.3, WT, 3.40), T_CONC, "y",
        rough=0.9, color=[0.66, 0.66, 0.62], solid=True)
    for x in (34.0, 40.0, 48.0, 55.0):
        troffer("S3d_tr%.0f" % x, x, Y3 + 4.60, 202.0,
                on=(x in (34.0, 55.0)), size=(1.10, 0.28))

    # ================================================================ R4 上の部屋
    shell("S3e", 58.0, 72.0, 196.0, SZ1, H4, T_CONC, T_PAINT, y=Y4, walls="es",
          ceil_tex=T_CEIL, floor=False)
    # ★床は z=210.0 で止める。その先(〜213.95)は継ぎ目16 が生やす出口の床の居場所
    box("S3e_flr", (65.0, Y4 - WT / 2, (195.7 + 210.0) / 2), (14.6, WT, 210.0 - 195.7),
        T_CONC, "y", rough=0.95, solid=True)
    box("S3e_pit", (65.0, Y4 - 1.60 - WT / 2, 212.0), (14.0, WT, 4.0), T_CONC, "y",
        rough=0.95, solid=True)
    for sgn, xx in ((-1, 58.0), (1, 72.0)):
        box("S3e_pw%d" % sgn, (xx, Y4 - 0.80, 212.0), (0.10, 1.60, 4.0), T_TILEW, "x", rough=0.4)
    box("S3e_pf", (65.0, Y4 - 0.80, 209.95), (14.0, 1.60, 0.10), T_TILEW, "z", rough=0.4)
    # ★継ぎ目14 の褒美は【塞ぎ板が退く】こと。渡す物ばかりだと単調になるので、
    #   ここだけ「道が空く」形にした(検査は mover を消して通れるかを見る)。
    S3E_BLK = box("S3e_blk", (65.0, Y4 + 1.10, 207.0), (14.0, 2.20, 0.24), T_METAL, "z",
                  rough=0.5, metal=0.5, color=[0.46, 0.46, 0.44], solid=True, tile=(7.0, 1.1))
    wall_hole("S3e_w", "x", 58.0 - WT / 2, 196.0 - WT, SZ1 + WT, Y4, Y4 + H4,
              202.0, 2.60, Y4, 2.40, T_PAINT)
    wall_hole("S3e_n", "z", SZ1 + WT / 2, 58.0 - WT, 72.0 + WT, Y4, Y4 + H4,
              XITX, XITW, Y4, XITH, T_PAINT)
    for z in (200.0, 206.0, 211.0):
        troffer("S3e_tr%.0f" % z, 62.0, Y4 + H4, z, on=(z != 206.0))

    # ---- 継ぎ目 14「直視しない」----
    # ★正面で見ると絶対に決まらない。目の端に置いたまま歩く。
    F14 = (61.20, EY4, 200.60)
    c14 = Conn(14, F14, 3.6, 13.0, (67.2, Y4 + 2.3, 204.1), "canopy-peri",
               needs=(13,), peri=True,
               min_y=EY4 - 0.6, max_y=EY4 + 0.6)
    for i, k in enumerate((0.40, 0.62)):
        zz = 203.2 + 1.9 * i
        pl = box("C14_p%d" % i, (67.20, Y4 + 2.30, zz), (3.20, 0.22, 1.70), T_METAL, "y",
                 rough=0.5, metal=0.5, color=[0.50, 0.50, 0.47], tile=(1.6, 0.85))
        br = box("C14_b%d" % i, (68.60, Y4 + 1.75, zz), (0.16, 1.10, 0.16), T_METAL, "x",
                 rough=0.5, metal=0.6, color=[0.44, 0.44, 0.42])
        g = glow("C14_g%d" % i, (65.70, Y4 + 2.44, zz), (0.05, 0.04, 1.50), GOLD, 1.05)
        c14.shard(k, [pl, br, g], glows=[g])
    # 庇が架かると、北を塞いでいた板が巻き上がる
    c14.mover_by(S3E_BLK, (0.0, 2.60, 0.0), dur=1.7, delay=0.35)
    mark("C14_mark", (F14[0], Y4 + 0.008, F14[2]), T_CONC, (0.74, 0.74, 0.72), rough=0.9)
    plight("C14_fill", (63.0, Y4 + 2.6, 202.0), WARM, 8.0, 12.0)

    # ---- 継ぎ目 16「暗の一瞬」----
    # ★位置を合わせてから、明かりが落ちる 1 秒を待つ。合わせると出口の床が生える。
    F16 = (63.60, EY4, 208.60)
    DARK3 = []
    for bx3 in (61.0, 67.0):
        nm3 = "C16_bk%.0f" % bx3
        troffer(nm3, bx3, Y4 + H4, 208.6, on=True, intensity=10.0, rng=13.0)
        DARK3.append(nm3)
    c16 = Conn(16, F16, 3.6, 12.0, (XITX, Y4 + 0.4, SZ1 - 2.0), "model-dark",
               needs=(14,), dark=True, dark_lights=DARK3)
    # ★z 210.0〜213.95 の隙間を【ぴったり】3 枚で埋める。隙間が残ると渡れない
