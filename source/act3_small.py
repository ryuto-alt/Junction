def build(G, Y3, DW, DH):
    """G は gen_liminal モジュール。名前空間を汚さないよう明示的に受け取る。"""
    box, glow, hit, plight = G.box, G.glow, G.hit, G.plight
    wall_with_door, wall_hole, slab = G.wall_with_door, G.wall_hole, G.slab
    troffer, mark, ent, Conn = G.troffer, G.mark, G.ent, G.Conn
    door_casing, exit_sign, bench, locker = G.door_casing, G.exit_sign, G.bench, G.locker
    T_CONC, T_PAINT, T_METAL = G.T_CONC, G.T_PAINT, G.T_METAL
    T_TILEW, T_CEIL, T_LAMP = G.T_TILEW, G.T_CEIL, G.T_LAMP
    guide_sign, SIGN_Y = G.guide_sign, G.SIGN_Y
    WT, EYE, GOLD, WARM = G.WT, G.EYE, G.GOLD, G.WARM
    FRAME_COL = G.FRAME_COL

    L0 = Y3                  # 5.80  R1 の床
    L1 = Y3 + 0.90           # 6.70  R2 の床
    L2 = Y3 + 1.80           # 7.60  R3 / 廊下 / R5 の床 = 出口の高さ(Y4)
    E0, E1, E2 = L0 + EYE, L1 + EYE, L2 + EYE
    SZ0, SZ1 = 172.0, 214.0
    XITX, XITW, XITH = 68.0, 2.20, 2.40
    CIL_A = 9.90             # R1+R2 の天井(R1 は 4.10m / R2 は 3.20m)
    CIL_C = 11.20            # R3 の天井(3.60m)
    CIL_D = 11.10            # 廊下の天井(3.50m)
    CIL_E = 11.40            # R5 の天井(3.80m)

    # ================================================================ R1+R2 の殻
    # ★側壁は R1 と R2 で【1 枚に通す】。部屋ごとに shell を建てると、壁が
    #   WT ぶん重なって同一平面になり、机上検査[6](ちらつき)で落ちる。
    for sgn, nm in ((-1, "w"), (1, "e")):
        box("S3ab_%s" % nm, (23.0 + sgn * (7.0 + WT / 2), (L0 + CIL_A) / 2, (171.70 + 201.00) / 2),
            (WT, CIL_A - L0, 201.00 - 171.70), T_PAINT, "x", rough=0.9, solid=True)
    box("S3ab_cil", (23.0, CIL_A + WT / 2, (171.70 + 201.00) / 2),
        (14.6 + WT * 2, WT, 201.00 - 171.70), T_CEIL, "y", rough=0.94)

    # ---------------------------------------------------------------- R1 枠の廊下
    box("S3a_flr", (23.0, L0 - WT / 2, (171.70 + 185.90) / 2), (14.6, WT, 185.90 - 171.70),
        T_CONC, "y", rough=0.95, solid=True)
    wall_with_door("S3a_s", "z", SZ0 - WT / 2, 15.70, 30.30, L0, CIL_A - L0, 22.0, DW, DH, T_PAINT)
    # ★白い部屋(第二幕)の床は z=170.3 で終わる。渡りを 1 枚だけ、ぴったり足す
    box("S3a_in", (22.0, L0 - WT / 2, 171.0), (3.6, WT, 1.4), T_CONC, "y", rough=0.95, solid=True)
    box("S3a_incil", (22.0, L0 + 2.9 + WT / 2, 171.0), (3.6, WT, 1.4), T_CONC, "y", rough=0.94)
    for sgn in (-1, 1):
        box("S3a_inw%d" % sgn, (22.0 + sgn * 1.9, L0 + 1.45, 171.0), (WT, 2.9, 1.4),
            T_CONC, "x", rough=0.9, solid=True)
    # 北の戸口。★下端は【床の高さ】に取る。開口の下に壁を残すと、継ぎ目11 の段が
    #   その壁へめり込む(検査[8])。段差は R2 の床が 0.90 上にあることで作る。
    wall_with_door("S3a_n", "z", 186.0 + WT / 2, 15.70, 30.30, L0, CIL_A - L0,
                   23.0, 2.80, 3.30, T_PAINT)
    door_casing("S3a_nc", "z", 186.0 - 0.03, 23.0, L0, 2.80, 3.30)
    # 間仕切り(くびれ)。★枠はこの真ん中に立てる = 通ろうとして必ず一度は覗く
    # ★★実機で「頭上に黒い変なものがある」と言われた直し(2026-09-09)。
    #   前は床から天井まで【全高】で立っていて、入口から北を見ると
    #   奥の灯りを背負った【光の当たらない大きな平面】になっていた。
    #   この作品の壁は全部「灯りの縞」で読ませているので、真っ黒な面が 1 枚あるだけで
    #   そこだけ異物になる。→ 背丈ほど(1.80m)で止めて【上を開ける】。
    #   天井の灯りが上を越して入るので、面が黒い板にならない。
    #   天端に明るい見切りを 1 本入れて、平坦な面のままにしない。
    for nm, x0, x1 in (("pw0", 15.70, 20.60), ("pw1", 25.40, 30.30)):
        box("S3a_" + nm, ((x0 + x1) / 2, L0 + 0.90, 181.20), (x1 - x0, 1.80, WT),
            T_PAINT, "z", rough=0.9, solid=True)
        box("S3a_%sc" % nm, ((x0 + x1) / 2, L0 + 1.84, 181.20), (x1 - x0 + 0.10, 0.10, WT + 0.10),
            T_PAINT, "z", rough=0.45, color=[0.78, 0.76, 0.70])
    for z, on in ((175.0, True), (178.6, False), (183.4, True)):
        troffer("S3a_tr%.0f" % z, 23.0, CIL_A, z, on=on)
    bench("S3a_bench", 17.9, L0, 176.4, axis="z")
    locker("S3a_lk", 27.6, L0, 174.6, n=3, axis="z")
    # ---- 案内板「枠に収める」(第一幕の 3 枚と同じ額縁・同じ質感・同じ床 +2.24m) ----
    # ★なぜ要るか: 第三幕は 5 部屋とも【動詞が違う】。初めて立った人に規則を
    #   推測させるのは酷なので、第一幕と同じ「壁に貼った案内板」で 1 部屋 1 枚だけ言う。
    # ★合図にはしない。近づいても光らず、鳴らず、動かない。最初から貼ってあるだけ。
    # ★置き場所は【入口を出て左手の壁】。枠(z=181.20)より手前なので、仕掛けを
    #   見る前に読める。x=16.00 は西壁の面で、絵は 0.045 手前に出る。
    #   ★仕掛けの真横には貼らない。真横に貼ると「立ち位置を指す矢印」になる。
    #     立ち位置は床の金の印が既に言っている。板は【規則】だけを言う。
    guide_sign("S3a_sign", 16.00, L0 + SIGN_Y, 175.20, -90.0,
               "ui/signs/sign_fit_frame.png")

    # ---- 継ぎ目 11「枠に収める」──────────────────────────────────────────
    # ★この幕の【授業】。空の窓枠が間仕切りの真ん中に立っていて、避けて通れるが
    #   通ろうとすると必ず一度は覗く。枠の【手前】に 3 枚の幽霊が浮いているので、
    #   近づくと枠からはみ出し、下がると収まる ＝ 前後に歩くことが初めて仕事になる。
    # ★合図は一切無い。枠は最初からそこに立っている建物の一部でしかない。
    F11 = (23.00, E0, 176.20)
    # ★枠の内法は【一番手前の幽霊(1 段目)】で決まる。手前の物ほど大きく見えるので、
    #   そこがぎりだと【焦点ですら枠からはみ出す】= 確定域が焦点の手前側へ寄り切り、
    #   印が焦点を中心に置けなくなる(calib_marks が印を置けずに落ちた)。
    FR11_Y0, FR11_Y1 = L0 + 0.36, L0 + 1.92
    FR11_X0, FR11_X1, FR11_Z = 22.00, 24.00, 181.20
    c11 = Conn(11, F11, 3.4, 12.0, (23.0, L0 + 0.45, 184.60), "fit-in-frame",
               frame=[[FR11_X0, FR11_Y0, FR11_Z], [FR11_X1, FR11_Y0, FR11_Z],
                      [FR11_X1, FR11_Y1, FR11_Z], [FR11_X0, FR11_Y1, FR11_Z]])
    # 枠そのもの(見付 0.16 / 見込 0.22)。★腰から下は塞ぐ。枠をくぐれてしまうと
    #   「覗く物」ではなく「通る物」になり、動詞が壊れる
    box("S3a_frb", (23.00, L0 + 0.18, FR11_Z), (2.32, 0.36, 0.22), T_PAINT, "z",
        rough=0.45, color=FRAME_COL)
    for sgn in (-1, 1):
        box("S3a_frj%d" % sgn, (23.00 + sgn * 1.08, L0 + 1.22, FR11_Z), (0.16, 1.72, 0.22),
            T_PAINT, "z", rough=0.45, color=FRAME_COL)
    box("S3a_frh", (23.00, L0 + 2.00, FR11_Z), (2.32, 0.16, 0.22), T_PAINT, "z",
        rough=0.45, color=FRAME_COL)
    # 段は 3 枚。天端 +0.30 / +0.60 / +0.90 で、R2 の床(L1)へ上がりきる
    for i in range(3):
        z0 = 183.35 + i * 0.85
        top = L0 + 0.30 * (i + 1)
        st = box("C11_s%d" % i, (23.00, (L0 + top) / 2, z0 + 0.415), (2.60, top - L0, 0.83),
                 T_CONC, "y", rough=0.9, color=[0.62, 0.62, 0.58], tile=(0.42, 1.30))
        g = glow("C11_g%d" % i, (23.00, top + 0.021, z0 + 0.10), (2.30, 0.04, 0.05), GOLD, 1.05)
        c11.shard(0.48, [st, g], glows=[g])
        c11.solid(hit("C11_h%d" % i, (23.00, (L0 + top) / 2, z0 + 0.415),
                      (2.60, top - L0, 0.83), kinematic=True))
    mark("C11_mark", (F11[0], L0 + 0.008, F11[2]), T_CONC, (0.74, 0.74, 0.72), rough=0.9)
    plight("C11_fill", (23.0, L0 + 2.7, 182.6), WARM, 8.0, 12.0)
    # ★間仕切りの【手前の面】を照らす灯り。これが無いと奥の光を背負って
    #   黒い板に見える(実機で「頭上の黒い変なもの」と言われた)
    plight("C11_fil2", (23.0, L0 + 2.2, 179.4), WARM, 6.0, 9.0)

    # ================================================================ R2 並びの間
    box("S3b_flr", (23.0, L1 - WT / 2, (185.90 + 201.15) / 2), (14.6, WT, 201.15 - 185.90),
        T_CONC, "y", rough=0.95, solid=True)
    wall_with_door("S3b_n", "z", 201.15, 15.70, 30.30, L1, CIL_C - L1, 28.60, 2.40, 2.90, T_PAINT)
    for z, on in ((188.4, True), (192.2, False), (196.0, True), (199.6, False)):
        troffer("S3b_tr%.0f" % z, 21.0, CIL_A, z, on=on)
    for z in (190.0, 197.0):                 # 拍を入れる柱
        box("S3b_col%.0f" % z, (17.2, (L1 + CIL_A) / 2, z), (0.55, CIL_A - L1, 0.55),
            T_CONC, "x", rough=0.9, solid=True)
    # 歩廊へ上がる段(★最初から実在する。歩ける物は全部歩ける)
    # ★【西から東へ】上げること。南から北へ上げる向きにすると、段の手前は
    #   北壁も歩廊の庁も塞いでいて【一段目に乗れる升が一つも無い】(検査[2] で実測)。
    for i in range(3):
        top = L1 + 0.30 * (i + 1)
        box("S3b_st%d" % i, (26.515 + i * 0.633, (L1 + top) / 2, 187.50),
            (0.633, top - L1, 1.80), T_CONC, "y", rough=0.9, color=[0.64, 0.64, 0.60],
            solid=True, tile=(0.90, 0.32))
    # ---- 案内板「なぞる」。★戸口を抜けて左手、柱(x=17.2 z=190)の手前 ----
    #   歩廊(東側 x=29)を見る前に読める位置。振る動作だけを描いてあり、
    #   どこに立つかは描いていない(それは床の金の印の仕事)。
    guide_sign("S3b_sign", 16.00, L1 + SIGN_Y, 188.00, -90.0,
               "ui/signs/sign_sweep_gaze.png")
    # 北の戸口の敷居(実在)。歩廊が架かるまでは届かない
    box("S3b_land", (28.625, L2 - 0.11, 200.925), (2.25, 0.22, 0.75), T_CONC, "y",
        rough=0.9, color=[0.64, 0.64, 0.60], solid=True, tile=(0.38, 1.12))

    # ---- 継ぎ目 12「なぞる」──────────────────────────────────────────────
    # ★動詞が変わる。ここは【立ち止まって一点を待つ】のではなく、端から端へ
    #   首を振り切るのが仕事。照準が通った板から順に溶接される(待ち時間ゼロ)。
    # ★初見殺しにしない作り: 5 枚を 76 度に広げて置く。視野(26 度)には絶対に
    #   収まらないので、見ようとすれば必ず首が動く。そして 1 枚目が
    #   【振り向いた瞬間に】東の壁へ現れる ── 何をすればいいかが 1 秒で分かる。
    F12 = (20.60, E1, 193.60)
    c12 = Conn(12, F12, 2.9, 12.0, (29.00, L2 - 0.11, 194.00), "sweep-catwalk",
               needs=(11,), sweep=True)
    PLK_L = (13.00 - 4 * 0.06) / 5.0
    for i in range(5):
        z0 = 187.50 + i * (PLK_L + 0.06)
        zc = z0 + PLK_L / 2
        pl = box("C12_p%d" % i, (29.00, L2 - 0.11, zc), (1.80, 0.22, PLK_L),
                 T_METAL, "y", rough=0.5, metal=0.5, color=[0.50, 0.50, 0.47],
                 tile=(PLK_L / 2, 0.9))
        g = glow("C12_g%d" % i, (28.14, L2 + 0.02, zc), (0.05, 0.04, PLK_L - 0.16), GOLD, 1.05)
        c12.shard(0.42, [pl, g], glows=[g])
        c12.solid(hit("C12_h%d" % i, (29.00, L2 - 0.11, zc), (1.80, 0.22, PLK_L),
                      kinematic=True))
    mark("C12_mark", (F12[0], L1 + 0.008, F12[2]), T_CONC, (0.74, 0.74, 0.72), rough=0.9)
    plight("C12_fill", (24.0, L1 + 2.8, 193.6), WARM, 8.5, 14.0)
    plight("C12_fil2", (27.5, L1 + 2.6, 198.4), WARM, 6.0, 10.0)

    # ================================================================ R3 影の間
    box("S3c_flr", (23.0, L2 - WT / 2, 205.80), (14.6, WT, 9.00), T_CONC, "y",
        rough=0.95, solid=True)
    box("S3c_cil", (23.0, CIL_C + WT / 2, 205.80), (14.6 + WT * 2, WT, 9.00), T_CEIL, "y",
        rough=0.94)
    box("S3c_w", (15.85, (L2 + CIL_C) / 2, 205.80), (WT, CIL_C - L2, 9.00), T_PAINT, "x",
        rough=0.9, solid=True)
    box("S3c_n", (23.0, (L2 + CIL_C) / 2, 210.15), (14.6 + WT * 2, CIL_C - L2, WT), T_PAINT,
        "z", rough=0.9, solid=True)
    wall_hole("S3c_e", "x", 30.15, 201.30, 210.30, L2, CIL_C, 205.15, 2.60, L2, 2.40, T_PAINT)
    # 東の開口を塞ぐシャッター。継ぎ目13 が解けると床下へ沈む
    S3C_BLK = box("S3c_blk", (30.15, L2 + 1.20, 205.15), (0.26, 2.40, 2.60), T_METAL, "x",
                  rough=0.5, metal=0.5, color=[0.46, 0.46, 0.44], solid=True, tile=(1.2, 1.3))
    # ★天井の蛍光灯は全部死んでいる。灯りは南西の 1 本だけ ── これが影を作る
    for z in (203.4, 208.2):
        troffer("S3c_tr%.0f" % z, 23.0, CIL_C, z, on=False)
    LMP = (18.00, 10.90, 208.00)
    box("S3c_lampr", (LMP[0], (LMP[1] + CIL_C) / 2, LMP[2]), (0.06, CIL_C - LMP[1], 0.06),
        T_METAL, "y", rough=0.45, metal=0.7, color=[0.5, 0.5, 0.48])
    box("S3c_lampb", (LMP[0], LMP[1] + 0.08, LMP[2]), (0.30, 0.10, 0.30), T_METAL, "y",
        rough=0.45, metal=0.6, color=[0.46, 0.46, 0.44])
    glow("S3c_lampg", LMP, (0.22, 0.16, 0.22), [1.00, 0.95, 0.84], 2.4)
    plight("S3c_lampl", (LMP[0], LMP[1] - 0.22, LMP[2]), WARM, 11.0, 15.0)
    plight("S3c_amb", (24.0, L2 + 2.6, 205.0), WARM, 2.2, 9.0)   # 床が読める最低限
    # ---- 案内板「影を重ねる」。★5 枚の中でこれが一番効かないと困る 1 枚 ----
