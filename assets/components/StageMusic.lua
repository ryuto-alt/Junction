-- JUNCTION 本編の【どこかで鳴っている音楽】。
--
-- これは BGM ではない。廃墟のどこか遠くで何かが鳴っていて、それが壁越しに漏れてくる、
-- という【空間】を作るための仕掛け。だから音源は 3 つとも実際に世界の中に座標を持っていて、
-- ゆっくり動き続けている。
--
-- ★満たすべきことは 2 つだけ。この 2 つは相反するので、間を通すのが全部。
--     (1) 音源を特定させない。「音が大きい方へ行けば正解」になった瞬間に失敗。
--     (2) かといって変化しないと、それはただの BGM。方向と距離がゆっくり変わり続けること。
--   答は【方向と距離はいつの間にか変わっているのに、いつまでも辿り着けない】。
--
-- ★特定させないために効かせている仕掛けは 4 つ。どれか 1 つでも外すと崩れる:
--
--   (a) minDistance を極端に大きく取る(15〜16m)。
--       この半径の内側では音量が変わらない = 【大きさで距離が測れない】。
--       部屋 1 つはたいてい minD の内側に丸ごと入るので、部屋の中でどこへ動いても
--       音量は動かない。maxD は 90〜100m まで伸ばして falloff を長く薄くする。
--       ★部屋の唸り(Liminal.lua の buzz.wav)は minD 2.0 / maxD 13.0 で【真逆】。
--         あれは「この部屋の設備が鳴っている」= 位置が分かってよい音。取り違えないこと。
--
--   (b) 歩けない所にしか置かない。第1〜2幕は【床下】(y ≒ -10)、第2〜3幕は【天井裏】
--       (y ≒ +21.5)、第4〜5幕は【ピットの底のさらに下】(y ≒ -1.5)。
--       xz では部屋の真上・真下を平気で通るが、y で必ず外に出ている。
--       ★辿り着けてしまうと、そこで正体が確定して魔法が解ける。
--
--   (c) 止まらない。周転円(大きい円 + 小さい円)で漂わせる。2 つの周期を無理数比に近い
--       値(P2 ≒ P1 * 0.62)にしてあるので【軌道は二度と同じ所を通らない】。
--       覚えられない = 特定できない。
--       ★速さは最大でも 0.8m/s 前後。歩く速さ(3.8m/s)の 1/5 以下。これより速いと
--         「動いている物」として知覚されて正体がバレる。遅すぎると BGM になる。
--
--   (d) 仕掛けと無相関に置く。中心も軌道も、継ぎ目(C1〜C25)や焦点とは何の関係もない
--       所に取ってある。軌道は 1 周のあいだに幕を丸ごと跨ぐので、どの継ぎ目の近くにも
--       「いつも音源がいる」ということが起きない。
--
-- ★遮蔽は無い。エンジンに遮蔽処理が無いのはここでは好都合で、壁の向こうから染み出して
--   くる感じになる。壁ごしに聞こえるのが正しい。
--
-- ★幕をまたいで離して置いてあるので、境目では 2 つが薄く重なる。
--   z≒110(第1幕→第2幕)と z≒205(第3幕の東の通路)がその帯で、
--   前からと後ろから、上からと下から、同時に薄く鳴る。ここが一番「分からない」。
--
-- ★第1幕は導入なので薄い(いちばん近い音源でも 35m 以上先)。ただし
--   【奥へ行くほど濃くなる】単調な作りにはしていない。濃さが進行方向の合図に
--   なってはいけないので、濃さの山は幕の切れ目ではなく軌道の都合で来る。
--
-- ★リスナー位置は Liminal.lua が毎フレーム audio:setListener で更新している。
--   こちらは触らない(プレイヤーの位置も要らない)。
--
-- ★このスクリプトは stagedemo3.json の LM_Music に載る(source/gen_liminal.py が置く)。
--   Liminal.lua とは別のコンポーネントなので、幾何と継ぎ目の側には一切触れていない。

-- ================================================================ 調整するのはここだけ
-- ★実機で耳で詰める値は全部この節に集めてある。ここから下は基本いじらなくてよい。

-- ★★2026-09-09「stage 途中の BGM ぜんっぜん聞こえない」への直し。
--   素の音量 0.19〜0.22 に対して、音源は【シェルの外】＝床下 10m / 天井裏 10m に
--   置いてある。つまりどこに立っても最低 10〜18m 離れていて、そのうえ minD を
--   15m しか取っていなかったので、常に falloff の効いた領域で聴くことになっていた。
--   ＝ 一番大きく聞こえる場所ですら素の 2 割、という設定になっていた。
--   ★★さらに「まだ聞こえない」との指摘。原因は【置き場所】そのものだった。
--     床下 10m / 天井裏 10m というのは、音を隠すには良くても、届かせるには遠すぎた。
--     ユーザーの指示どおり【ステージの中】へ移す:
--       [1] 第一幕・継ぎ目04(出口)の端  [2] 第三幕の長い廊下  [3] 第四〜五幕
--     ★中へ入れても「どこで鳴っているか分からない」は死んでいない。minD を 26〜28m
--       取ってあるので、歩ける範囲がまるごと【音量一定の内側】に入る ＝ 近づいても
--       大きくならない。方向だけがゆっくり変わる。漂う幅も部屋に合わせて詰めた。
--   直したのは 2 つ。どちらも「近づくと大きくなる」を招かない方向で効かせる:
--     ・素の音量を 3.3 倍(0.20 → 0.68 前後)
--     ・minD を 15 → 24〜26m。歩ける範囲がまるごと【音量一定の内側】に入るので、
--       大きくなったぶん「音源の方向へ寄れば大きくなる」が起きない。
--       maxD も伸ばして、幕をまたいだ遠鳴りが痩せないようにした。
--   ★うるさければ下の VOL だけ下げれば全部いっぺんに下がる。
local VOL          = 1.00   -- 全体の音量。まず最初に触るのはここ。0.7 で全体が一段遠のく
local START_DELAY  = 1.2    -- 場面が開いてから鳴り始めるまで(秒)。幕開けと同時に鳴らさない
local FADE_IN      = 6.0    -- 無音から定常までの秒数。長いほど「気づいたら鳴っていた」
                            -- ★14 秒は長すぎた。歩き出して 10 秒は無音同然で、
                            --   「鳴っていない」としか思えなかった
local BREATHE      = 0.06   -- 音量のごくゆっくりした揺れ(±6%)。0 で切れる
local BREATHE_P    = 97.0   -- その周期(秒)。素数めいた半端な値にして拍を作らない
local RESTART_CHECK= 8.0    -- 落ちた音源を鳴らし直す間隔(秒)。0 で切れる
                            -- ★もし曲が数秒おきに頭出しし直すように聞こえたら、
                            --   isVoicePlaying が当てにならない版。ここを 0 にすること。

-- 音源の表。座標は全部ワールド。c = 軌道の中心(音源が【絶対に居ない】点)。
--   rx/rz  … 大きい円の半径      rx2/rz2 … 重ねる小さい円の半径(合計が振れ幅)
--   ry     … 上下の揺れ幅        p1/p2/p3 … 大円 / 小円 / 上下 の周期(秒)
--   minD   … この内側では音量一定 = 距離が測れない半径
--   maxD   … ここまで届く。長く薄く
--   vol    … 素の音量(VOL が掛かる)   pitch … 1.0 からわずかにずらすと正体が薄れる
--   ph     … 位相。決め打ち(毎回同じに再現できるほうが耳で詰めやすい)
local SRC = {
    {   -- [1] 第一幕・継ぎ目04(出口)の【端】。廊下 D の東寄り、天井のすぐ下。
        --     ★出口の扉は (6.10, 4.50, 80.15)。廊下 D は x 4.60〜7.60 / 床 3.40 / 天井 6.15。
        --       その東の隅、扉の少し手前に置く ＝ 出口の「端」。
        name = "出口の端",         path = "audio/bgm/stage1.mp3",
        c = { 7.25, 5.40, 79.30 },
        rx = 0.9, rx2 = 0.4,  rz = 5.0, rz2 = 2.0, ry = 0.5,
        p1 = 420.0, p2 = 260.0, p3 = 190.0, ph = 0.0,
        minD = 26.0, maxD = 140.0, vol = 0.78, pitch = 1.00,
    },
    {   -- [2] 第三幕の長い廊下(継ぎ目14)。天井の照明の高さ。
        --     ★S3d の蛍光灯が y=10.75 / z=205.15 に並んでいる。その列の中ほど。
        --       第二幕の終わりから第三幕の奥までを一本で受け持つ。
        name = "廊下の奥",         path = "audio/bgm/stage2.mp3",
        c = { 48.0, 10.40, 205.15 },
        rx = 6.0, rx2 = 2.0,  rz = 1.2, rz2 = 0.6, ry = 0.6,
        p1 = 380.0, p2 = 235.0, p3 = 165.0, ph = 2.1,
        minD = 28.0, maxD = 150.0, vol = 0.80, pitch = 0.98,
    },
    {   -- [3] 第4幕〜第5幕。【ピットの底のさらに下】(G1_pit の上面 y=3.0 より下)
        --     ★1 と同じ曲。200m 離れているので混ざらない。奥まで来てまた同じものが
        --       遠くで鳴っている = 結局どこにも辿り着いていない、という手触り
        name = "低い方(再)",      path = "audio/bgm/stage1.mp3",
        c = { 69.0, 8.0, 250.0 },
        rx = 8.0, rx2 = 3.0,  rz = 14.0, rz2 = 5.0,  ry = 1.5,
        p1 = 330.0, p2 = 205.0, p3 = 145.0, ph = 4.3,
        minD = 26.0, maxD = 140.0, vol = 0.74, pitch = 1.00,
    },
}

-- ================================================================ ここから実装
local TAU = math.pi * 2.0

local function clamp(v, lo, hi) return math.max(lo, math.min(hi, v)) end

-- 周転円。大きい円の上を小さい円が別の周期で回る。
-- ★p2 を p1 の 0.62 倍あたりに取ってあるので比が有理数から遠く、軌道が閉じない
--   = 同じ所を二度通らない = 聞き覚えができない。
local function posOf(s, t)
    local a = t * TAU / s.p1 + s.ph
    local b = t * TAU / s.p2 + s.ph * 1.7
    local c = t * TAU / s.p3 + s.ph * 0.6
    return s.c[1] + s.rx * math.sin(a) + s.rx2 * math.sin(b),
           s.c[2] + s.ry * math.sin(c),
           s.c[3] + s.rz * math.cos(a) + s.rz2 * math.cos(b)
end

-- 今この音源が出すべき音量。生まれてからの時間で立ち上げ、そのあとは呼吸だけ。
-- ★立ち上がりは各音源が【自分の誕生時刻から】数える(鳴らし直したときも同じ手当てになる)
-- ★下限を 0 にしない(FLOOR)。音量ちょうど 0 の発声を「もう要らない」と畳む実装だと、
--   立ち上がりきる前に音源ごと消えてしまう。0.02 なら耳には無音のまま生き残る。
local FLOOR = 0.02
local function gainOf(self, i, s)
    local age = self.t - (self.born[i] or self.t)
    local k = FLOOR + (1.0 - FLOOR) * clamp(age / FADE_IN, 0.0, 1.0)
    local br = 1.0 + BREATHE * math.sin(self.t * TAU / BREATHE_P + s.ph)
    return VOL * s.vol * k * br
end

local function spawn(self, i)
    local s = SRC[i]
    local x, y, z = posOf(s, self.t)
    local id = nil
    -- ★出だしは gainOf の下限と同じ値。ここだけ 0 にすると 1 フレーム分だけ
    --   段が付くし、0 を「既定値」と解釈する版があっても困る。
    local ok = pcall(function()
        id = audio:playSpatialId(s.path, x, y, z, s.minD, s.maxD, VOL * s.vol * FLOOR, true)
    end)
    if not ok or not id then
        logWarn("StageMusic: 鳴らせません: " .. s.path)
        return
    end
    self.v[i] = id
    self.born[i] = self.t
    if math.abs(s.pitch - 1.0) > 0.001 then
        pcall(function() audio:setVoicePitch(id, s.pitch) end)
    end
end

function OnStart(self)
    self.t     = 0.0
    self.v     = {}      -- 音源 id
    self.born  = {}      -- その音源が鳴り始めた時刻(立ち上がりに使う)
    self.up    = false   -- 起動済みか
    self.chk   = 0.0     -- 生存確認の時計

    -- ★タイトル曲をここで【必ず】切る。タイトル → ロード画面 と鳴り続けてきた
    --   title.mp3 が本編まで漏れると台無しになる。ロード画面側でも音量を絞って
    --   あるが、絞り残しや経路違い(直接 stagedemo3 を Play した等)でも効くように、
    --   本編の入口であるここで無条件に止める。
    -- ★止めたあと BGM の音量つまみは 1.0 へ戻す。ロード画面が 0 まで下げたまま
    --   置いていくので、戻さないと次にタイトルへ帰ったとき無音になる。
    pcall(function()
        audio:stopBGM()
        audio:setBGMVolume(1.0)
    end)
end

function OnUpdate(self, dt)
    self.t = self.t + dt

    -- 幕開けと同時には鳴らさない。少し遅らせてから、さらに FADE_IN 秒かけて滲ませる。
    -- ★Liminal 側が 17 個の唸りを確保し終わってから割り込む、という意味もある
    if not self.up then
        if self.t < START_DELAY then return end
        self.up = true
        for i = 1, #SRC do spawn(self, i) end
    end

    for i = 1, #SRC do
        local id = self.v[i]
        if id then
            local s = SRC[i]
            local x, y, z = posOf(s, self.t)
            audio:moveVoice(id, x, y, z)
            audio:setVoiceVolume(id, gainOf(self, i, s))
        end
    end

    -- 落ちていたら鳴らし直す。mp3 のループが版によって効かないことがあるので保険。
    -- ★十分に育った音源だけを見る(生まれた直後は再生状態がまだ立っていないことがある)
    if RESTART_CHECK > 0.0 then
        self.chk = self.chk + dt
        if self.chk >= RESTART_CHECK then
            self.chk = 0.0
            for i = 1, #SRC do
                local id = self.v[i]
                local age = self.t - (self.born[i] or self.t)
                if id and age > FADE_IN then
                    local alive = true
                    pcall(function() alive = audio:isVoicePlaying(id) end)
                    if alive == false then
                        pcall(function() audio:stopVoice(id) end)  -- 二重に積まない
                        self.v[i] = nil
                        spawn(self, i)
                    end
                end
            end
        end
    end
end
