local END_GRACE    = 22.0   -- 戸口は越えたのに奥まで来ない人の保険(秒)
local WHITE_T0     = 0.55   -- 白い板が乗り始めるまで(秒)
local WHITE_RISE   = 1.85   -- 板が真っ白になりきるまで(秒)
local WHITE_HOLD   = 0.60   -- 真っ白のまま持たせてから場面を切る(秒)
local EXP_BLOW     = 3.20   -- 白飛びの exposure。★乗算・中立 1.0
