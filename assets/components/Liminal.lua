-- (smooth は補間用だった。つながる演出を全部やめたので、いま使うのは昇降床だけ)
local function smooth(t) t = clamp(t, 0, 1) return t * t * (3 - 2 * t) end

-- 対応点への視線の角度差(度)の最大値。atan2 版で 0 付近も安定して出る
-- ★Lua 5.4 は math.atan2 が消えて math.atan(y,x) になった。両方で動くようにする
local atan2 = math.atan2 or math.atan
local function alignError(ex, ey, ez, F, k, pts, ox, oy, oz)
    local worst = 0.0
    ox, oy, oz = ox or 0, oy or 0, oz or 0
    for i = 1, #pts do
        local p = pts[i]
        local ax, ay, az = p[1] - ex, p[2] - ey, p[3] - ez
        local bx = F[1] + k * (p[1] - F[1]) + ox - ex
        local by = F[2] + k * (p[2] - F[2]) + oy - ey
        local bz = F[3] + k * (p[3] - F[3]) + oz - ez
        local cx = ay * bz - az * by
        local cy = az * bx - ax * bz
        local cz = ax * by - ay * bx
        local cross = math.sqrt(cx * cx + cy * cy + cz * cz)
        local dot = ax * bx + ay * by + az * bz
        local d = math.deg(atan2(cross, dot))
        if d > worst then worst = d end
    end
    return worst
end

-- 規則F「かくれて合わせる」: 指定した点が【何かの陰に隠れている】か。
-- ★偽物が見えている限り決まらない継ぎ目に使う。目 -> 点 の線分が遮蔽箱を通れば「隠れた」。
--   机上検査(sim_liminal.occluded)と必ず同じ式にしておくこと。
local function hidden(occl, ex, ey, ez)
    local p = occl.p
    local o = {ex, ey, ez}
    local d = {p[1] - ex, p[2] - ey, p[3] - ez}
    for i = 1, #occl.boxes do
        local b = occl.boxes[i]
        local t0, t1, ok = 0.0, 1.0, true
        for a = 1, 3 do
            if math.abs(d[a]) < 1e-9 then
                if o[a] < b[a] or o[a] > b[a + 3] then ok = false break end
            else
                local ta = (b[a] - o[a]) / d[a]
                local tb = (b[a + 3] - o[a]) / d[a]
                if ta > tb then ta, tb = tb, ta end
                if ta > t0 then t0 = ta end
                if tb < t1 then t1 = tb end
                if t0 > t1 then ok = false break end
            end
        end
        if ok then return true end
    end
    return false
end

-- 2 点が【画面上で重なって見えるか】の角度差(度)。「触れる」規則で使う。
-- ★これは焦点を使わない。見えている 2 つの物を一直線に並べるだけなので、
--   隠された焦点を探す規則よりずっと読みやすい ＝ 別の考え方の puzzle になる。
-- ★スリット越しに見えているか。筒の中に的があり、目は外に居る前提。
--   線分 目→的 は筒の壁を【一度だけ】横切るので、その交点の角度が
--   いまのスリットの窓に入っているかを見るだけでよい。
--   ★筒を箱の集まりで近似しない。回る物を軸並行の箱で表すと嘘になる(hidden() が使えない)。
local function throughSlot(sl, yawNow, ex, ez, cx, cz)
    local dx, dz = cx - ex, cz - ez
    local ox, oz = ex - sl.c[1], ez - sl.c[2]
    local A = dx * dx + dz * dz
    local B = 2.0 * (ox * dx + oz * dz)
    local C = ox * ox + oz * oz - sl.r * sl.r
    local disc = B * B - 4.0 * A * C
    if disc <= 0.0 or A < 1e-9 then return false end        -- 筒に当たらない = 中は見えない
    local t = (-B - math.sqrt(disc)) / (2.0 * A)
    if t <= 0.0 or t >= 1.0 then return false end
    local px, pz = ox + t * dx, oz + t * dz                 -- 交点(筒の中心を原点に)
    local ang = math.deg(atan2(pz, px))
    -- モデルの局所角 a は、yaw θ で world では a - θ に見える
    -- ★★2026-09-09「回るやつ、まじ判定厳しい」への直し(本命)。
    --   スリットを【180 度対称に 2 本】開けたものとして判定する。
    --   どちらか一方は常にこちらを向いているので、判定は筒の角度に依存しなくなる。
    --
    --   何が変わるか:
    --     絵      … 筒は今までどおり回り続ける(あの絵は捨てない)
    --     動詞    … 「窓が開くのを【待つ】」から「見える所まで【歩く】」へ
    --     見え方  … 破片が見えるのが時間の 9.4% から【常時】になる
    --     手応え  … 立ち位置を直した結果が最大 10 秒後ではなく【即座】に分かる
    --
    --   ★これは楽にしているのではない。スリット越しに 3 つの塊が全部覗ける
    --     立ち位置は、筒の半径とスリットの幅から【床の上に一意に決まる】。
    --     時間の窓が空間の窓に変わっただけで、探す仕事は残っている。
    --   ★時間で待たせる規則は既に 2 本ある(暗の一瞬。継ぎ目 16 と 25)。
    --     筒も同じ「待つ」だと、絵が違うだけで手は同じになってしまっていた。
    local want = SLOT_MID - yawNow
    local d2 = ((ang - want + 180.0) % 360.0) - 180.0
    if math.abs(d2) < sl.half then return true end
    local d3 = ((ang - want) % 360.0) - 180.0        -- 反対側のスリット
    return math.abs(d3) < sl.half
end

-- ================================================================ 規則「枠に収める」
-- ★★2026-09-09 第三幕の作り直しで足した規則。回る筒を「時間の窓」から
--   【空間の窓】へ直したのと、まったく同じ考え方の一般形。
--   筒のスリットが円筒の窓なら、これは【床に立っている四角い窓】。
--
--   やること: 目 E と枠の 4 隅が作る四角錐の中に、破片が【全部】入っているか。
--   4 つの側面の法線との内積の符号が揃うかを見るだけで、カメラ行列も射影も要らない。
--
--   なぜ動詞が違うのか:
--     これまでの継ぎ目は「点(焦点)を探す」だった。枠は【面】なので、探す対象が
--     「枠と破片を結ぶ四角錐」になる。枠より手前に浮いている破片は、近づくと
--     枠からはみ出し、下がると枠に収まる ＝【前後に歩くことに初めて意味が出る】。
--
--   ★合図は出さない。枠は最初から部屋に立っている物で、光りも鳴りもしない。
--     枠は通り道の真ん中に立てること(避けて通れるが、通ろうとして必ず一度覗く)。
--   ★机上検査(sim_liminal.framed)と必ず同じ式にしておくこと。
local function insideFrame(fr, ex, ey, ez, px, py, pz)
    local s0 = nil
    for i = 1, 4 do
        local a, b = fr[i], fr[i % 4 + 1]
        local ax, ay, az = a[1] - ex, a[2] - ey, a[3] - ez
        local bx, by, bz = b[1] - ex, b[2] - ey, b[3] - ez
        local nx = ay * bz - az * by
        local ny = az * bx - ax * bz
        local nz = ax * by - ay * bx
        local d = nx * (px - ex) + ny * (py - ey) + nz * (pz - ez)
        if s0 == nil then s0 = (d >= 0.0)
        elseif (d >= 0.0) ~= s0 then return false end
    end
    return true
end

-- 破片の【浮遊姿勢】の 8 隅が、全部 枠の中に見えているか。
-- ★見えている物(幽霊)で判定する。焦点に立てば幽霊と実体は同じ方向に重なるので、
--   「幽霊が枠に収まる」＝「実体が枠に収まる」。表示と判定が食い違わない。
local function framedAll(c, ex, ey, ez)
    for s = 1, #c.shards do
        local sh = c.shards[s]
        local k, F = sh.k, sh.F
        for i = 1, #sh.pts do
            local p = sh.pts[i]
            if not insideFrame(c.frame, ex, ey, ez,
                               F[1] + k * (p[1] - F[1]),
                               F[2] + k * (p[2] - F[2]),
                               F[3] + k * (p[3] - F[3])) then
                return false
            end
        end
    end
    return true
end

-- ================================================================ 規則「影を重ねる」
-- ★この作品で唯一【照準を使わない】足切り。目をつぶっていても満たせる。
--   灯り L から見た自分(目の位置)の、床への投影が、床に描かれた輪郭の中に入るか。
--   式は gen_liminal.floor_shadow() と同じ相似変換で、焦点を灯り・破片を自分に
--   置き換えただけ。
-- ★合図ではない。輪郭も灯りも最初から部屋にあり、近づいても何も起きない。
--   影そのものは runtime が薄い板で描く(castShadows は使わない)。
local function shadowPoint(sd, ex, ey, ez)
    local L = sd.L
    local dy = ey - L[2]
    if dy > -0.20 then return nil end          -- 目が灯りより上 = 床に落ちない
    local t = (sd.fy - L[2]) / dy
    return L[1] + t * (ex - L[1]), L[3] + t * (ez - L[3])
end

local function shadowHits(sd, ex, ey, ez)
    local sx, sz = shadowPoint(sd, ex, ey, ez)
    if not sx then return false end
    local dx, dz = sx - sd.c[1], sz - sd.c[2]
    local ca = math.cos(math.rad(sd.yaw))
    local sa = math.sin(math.rad(sd.yaw))
    local u = dx * ca - dz * sa
    local v = dx * sa + dz * ca
    return math.abs(u) <= sd.w * 0.5 and math.abs(v) <= sd.l * 0.5
end

local function pairAngle(ex, ey, ez, a, b)
    local ax, ay, az = a[1] - ex, a[2] - ey, a[3] - ez
    local bx, by, bz = b[1] - ex, b[2] - ey, b[3] - ez
    local cx = ay * bz - az * by
    local cy = az * bx - ax * bz
    local cz = ax * by - ay * bx
    return math.deg(atan2(math.sqrt(cx * cx + cy * cy + cz * cz),
                          ax * bx + ay * by + az * bz))
end

-- u = 0 で【浮遊姿勢】、u = 1 で【実体】。
--   通常の破片は焦点まわりの相似変換(k -> 1)。
--   disp を持つ破片(「触れる」規則用)は、相似の縛りが無い自由な浮遊姿勢からの補間。
-- ★★未実体の破片は【半透明の幽霊】で置いてある(assets/shaders/Unbuilt.hlsl)。
--   透けている物には乗れない、と一目で分かる = 当たり判定の有無と見た目が必ず一致する。
--   確定したらここで不透明の本物へ戻す。
--   ★これは合図ではない。近づいても狙っても変わらず、確定の瞬間に 1 回だけ切り替わる。
--     合っているかどうかは今までどおり【破片の重なり】だけで判断させる。
-- ★★2026-09-09「つながったかどうか分かりにくい」の修正。
--   これまでは effectValue を 1.0 へ書いて終わり ＝ パチンと不透明になるだけだった。
--   ここでは 2.0 を書き、runShards が毎フレーム 1.0 へ向けて落としていく。
--   Unbuilt.hlsl は 1 を超えた分を「つながった直後の残り時間」と読み、
--   輪郭から内側へ光を 1 度だけ走らせる(0.9 秒で消える)。
-- ★合図ではない。ここへ来る時には破片はもう実体の位置に収まっている ＝
--   近づいている最中には何も起きない。結果だけを、後から短く伝える。
local function solidify(sh)
    if sh.solidDone then return end
    sh.solidDone = true
    sh.showT = 0.0                -- 0 -> 1。runShards が進める
    for i = 1, #sh.ents do
        local r = sh.ents[i]
        if r.e and r.e:isValid() then
            pcall(function() scene:setMeshEffect(r.e, 2.0) end)
        end
    end
end

-- つながった直後の光。effectValue を 2.0 -> 1.0 へ落とすだけ(形は全部シェーダー側)
local function runWeldShow(sh, dt)
    if not sh.showT or sh.showT >= 1.0 then return end
    sh.showT = math.min(sh.showT + dt / WELD_SHOW, 1.0)
    local v = 2.0 - sh.showT       -- ★終わりは 1.0 ちょうど = 旧来の「本物」に戻る
    for i = 1, #sh.ents do
        local r = sh.ents[i]
        if r.e and r.e:isValid() then
            pcall(function() scene:setMeshEffect(r.e, v) end)
        end
    end
end

local function applyShard(sh, u, ox, oy, oz)
    ox, oy, oz = ox or 0, oy or 0, oz or 0
    if sh.disp then
        local w = 1.0 - u
        local sc = 1.0 + (sh.dk - 1.0) * w
        for i = 1, #sh.ents do
            local r = sh.ents[i]
            if r.e then
                r.e.transform.position = V(r.p[1] + sh.disp[1] * w + ox,
                                           r.p[2] + sh.disp[2] * w + oy,
                                           r.p[3] + sh.disp[3] * w + oz)
                r.e.transform.scale = V(r.s[1] * sc, r.s[2] * sc, r.s[3] * sc)
            end
        end
        return
    end
    local F = sh.F
    local kk = sh.k + (1.0 - sh.k) * u
    for i = 1, #sh.ents do
        local r = sh.ents[i]
        if r.e then
            r.e.transform.position = V(F[1] + kk * (r.p[1] - F[1]) + ox,
                                       F[2] + kk * (r.p[2] - F[2]) + oy,
                                       F[3] + kk * (r.p[3] - F[3]) + oz)
            r.e.transform.scale = V(r.s[1] * kk, r.s[2] * kk, r.s[3] * kk)
        end
    end
end

-- 揺れる破片。★合う姿勢(o=0)で【速度も 0 になる】式にすること。
--   ここが最速だと「合う瞬間」が一瞬すぎて理不尽になる。(1-cos)/2 なら端で止まる。
local function shardOffset(sh, t)
    local o = sh.osc
    if not o then return 0, 0, 0 end
    local w = (1.0 - math.cos(2 * math.pi * ((t / o[4]) % 1.0))) * 0.5
    return o[1] * w, o[2] * w, o[3] * w
end

